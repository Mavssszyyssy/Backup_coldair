// Creates disposable accounts only in the explicitly selected localhost QA DB.
// No live accounts, OTP email deliveries, or OpenAI calls are used.
const assert = require('node:assert/strict');
const path = require('node:path');
const jwt = require('jsonwebtoken');
const speakeasy = require('speakeasy');
require('dotenv').config({ path: path.join(__dirname, '..', '.env') });
const expectedDatabase = process.env.ACCEPTANCE_EXPECTED_DATABASE;
if (!/(_qa|_e2e)$/.test(expectedDatabase || '')) throw new Error('An explicitly named QA database is required.');
const base = 'http://127.0.0.1:5002/api';
let checks = 0;
const pass = text => { checks++; console.log(`PASS ${text}`); };
const request = async (route, token, body, method = body ? 'POST' : 'GET') => {
  const response = await fetch(base + route, { method, headers: { ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(body ? { 'Content-Type': 'application/json' } : {}) }, body: body ? JSON.stringify(body) : undefined, signal: AbortSignal.timeout(25000) });
  const data = await response.json();
  return { status: response.status, ...data };
};
const code = secret => speakeasy.totp({ secret, encoding: 'base32' });
async function exerciseRecovery(role, identifier, token, password) {
  const codes = await request('/security/recovery-codes/regenerate', token, {});
  assert.equal(codes.status, 200);
  const oldRead = await request('/auth/me', token); // also warm the old-session cache
  assert.equal(oldRead.status, 200);
  const recovered = await request('/security/recovery-codes/consume', null, { identifier, code: codes.codes[0].code });
  assert.equal(recovered.status, 200);
  assert.equal(recovered.recoveryDestination, `/${role}/oobe/reset`);
  assert.equal((await request('/users/profile', token)).status, 401);
  assert.equal((await request('/users/profile', recovered.token)).status, 403);
  assert.equal((await request('/security/recovery-codes/consume', null, { identifier, code: codes.codes[0].code })).status, 400);
  pass(`${role}: recovery consumes the code once, revokes old sessions, and restricts the recovery session`);
  const passwordLogin = await request('/auth/login', null, { identifier, password });
  assert.equal((await request('/users/profile', passwordLogin.token)).status, 403);
  pass(`${role}: password login cannot bypass an unfinished authenticator reset`);
  const setup = await request('/security/totp/setup', recovered.token, {});
  assert.equal(setup.status, 200);
  assert.equal((await request('/security/totp/verify', recovered.token, { code: '12345' })).status, 400);
  const verified = await request('/security/totp/verify', recovered.token, { code: code(setup.secret) });
  assert.equal(verified.status, 200);
  assert.equal(verified.user.security.totpResetRequired, false);
  assert.equal((await request('/users/profile', verified.token)).status, 200);
  assert.equal((await request('/security/totp/setup', recovered.token, {})).status, 401);
  pass(`${role}: authenticator reset restores access only with the newly issued session`);
  const challenge = await request('/auth/login', null, { identifier, password });
  assert.ok(challenge.requiresTotp && !challenge.token);
  assert.equal((await request('/users/profile', challenge.challengeToken)).status, 401);
  assert.equal((await request('/auth/login/totp', null, { challengeToken: challenge.challengeToken, code: code(setup.secret) })).status, 200);
  pass(`${role}: subsequent sign-in requires the replacement authenticator`);
  const racing = await Promise.all([1, 2].map(() => request('/security/recovery-codes/consume', null, { identifier, code: codes.codes[1].code })));
  assert.deepEqual(racing.map(item => item.status).sort(), [200, 400]);
  pass(`${role}: concurrent recovery requests cannot reuse a single code`);
}
async function main() {
  const health = await request('/health');
  assert.notEqual(health.environment, 'production');
  assert.equal(health.databaseName, expectedDatabase);
  const admin = await request('/auth/login', null, { identifier: 'superadmin.main', password: 'admin123' });
  assert.ok(admin.token);
  const run = String(Date.now()).slice(-8);
  const staff = await request('/users/staff', admin.token, { name_first: 'Security', name_last: 'QA', role: 'technician', branch: 'Bulacan', loginName: `sec${run}` });
  assert.equal(staff.status, 201);
  const tech = await request('/auth/login', null, { identifier: staff.loginIdentifier, password: staff.tempPassword });
  assert.equal((await request('/tasks', tech.token)).status, 403);
  assert.equal((await request('/users/profile', tech.token, { technicianOnboardedAt: new Date().toISOString() }, 'PATCH')).status, 409);
  const password = 'SecurityQa9!Air';
  const profile = await request('/users/password', tech.token, { alias: staff.loginIdentifier, phone: `0919${run.slice(-7)}`, newPassword: password }, 'PATCH');
  assert.equal(profile.status, 200);
  assert.equal(Boolean(profile.user.technicianOnboardedAt), false);
  assert.equal(profile.user.isFirstLogin, false);
  assert.equal((await request('/tasks', tech.token)).status, 403);
  pass('technician: saving profile/password cannot prematurely finish setup or open work orders');
  const setup = await request('/security/totp/setup', tech.token, {});
  const verified = await request('/security/totp/verify', tech.token, { code: code(setup.secret) });
  assert.equal(verified.status, 200);
  assert.ok(verified.user.technicianOnboardedAt);
  assert.equal((await request('/tasks', verified.token)).status, 200);
  assert.equal((await request('/tasks', tech.token)).status, 401);
  pass('technician: verified authenticator completes setup and retires the setup session');
  await exerciseRecovery('technician', staff.loginIdentifier, verified.token, password);
  const email = `security.${run}@example.test`;
  const verificationToken = jwt.sign({ purpose: 'registration_verification', email, phone: '' }, process.env.JWT_SECRET || 'dev-secret', { expiresIn: '5m' });
  const customer = await request('/auth/register', null, { name_first: 'Security', name_last: 'Customer', alias: `sec.customer.${run}`, email, password, registrationVerificationToken: verificationToken });
  assert.equal(customer.status, 200);
  const customerSetup = await request('/security/totp/setup', customer.token, {});
  const customerVerified = await request('/security/totp/verify', customer.token, { code: code(customerSetup.secret) });
  assert.equal(customerVerified.status, 200);
  await request('/users/profile', customerVerified.token, { customerOnboardedAt: new Date().toISOString() }, 'PATCH');
  await exerciseRecovery('customer', email, customerVerified.token, password);
  console.log(`Security acceptance completed: ${checks} checkpoints passed. QA accounts preserved; no live data changed.`);
}
main().catch(error => { console.error(`Security acceptance failed: ${error.message}`); process.exitCode = 1; });
